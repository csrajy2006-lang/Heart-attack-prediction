import streamlit as st
import pandas as pd
import joblib

# Load model
model = joblib.load("rfc_model.pkl")

st.title("❤️ Heart Attack Prediction App")

st.write("Enter Patient Details:")

# Input fields
age = st.number_input("Age", min_value=0)
gender_option = st.selectbox(
    "Gender",
    ("Female", "Male")
)
gender = 0 if gender_option == "Female" else 1

heart_rate = st.number_input("Heart rate")
sys_bp = st.number_input("Systolic blood pressure")
dia_bp = st.number_input("Diastolic blood pressure")
blood_sugar = st.number_input("Blood sugar")
ck_mb = st.number_input("CK-MB")
troponin = st.number_input("Troponin")
# Create dataframe
input_data = pd.DataFrame([[
    age,
    gender,
    heart_rate,
    sys_bp,
    dia_bp,
    blood_sugar,
    ck_mb,
    troponin
]], columns=model.feature_names_in_)

# -----------------------------
# Prediction
# -----------------------------

if st.button("Predict"):
    prediction = model.predict(input_data)[0]

    if prediction == "positive":
        st.error("⚠️ High Risk of Heart Attack")
    else:
        st.success("✅ Low Risk of Heart Attack")
